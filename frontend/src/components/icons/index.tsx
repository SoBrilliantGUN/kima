import type { SVGProps } from 'react'

export type IconProps = SVGProps<SVGSVGElement>

// 统一的图标外壳：viewBox / 描边风格默认值，尺寸交给外部 CSS（className）控制。
// 需要 fill 风格或非默认线宽的图标，在各具名组件内覆盖，消费方仍可通过 props 二次覆盖。
export function Icon({ children, ...rest }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...rest}
    >
      {children}
    </svg>
  )
}

